def build_user_prompt(
    text: str,
    *,
    has_links: bool,
    has_mentions: bool,
    is_forward: bool,
    group_topic: str,
    allowed_domains: str = "",
) -> str:
    parts: list[str] = []
    if group_topic:
        parts.append(
            f"Тематика группы: {group_topic}. "
            "Сообщения и даже реклама строго по этой теме — допустимы."
        )
    if allowed_domains:
        parts.append(f"Ссылки на эти домены считаются допустимыми: {allowed_domains}.")
    flags: list[str] = []
    if has_links:
        flags.append("содержит ссылки")
    if has_mentions:
        flags.append("содержит @упоминания")
    if is_forward:
        flags.append("это пересланное сообщение")
    flags.append("автор — новый участник без истории в группе")
    parts.append("Признаки: " + ", ".join(flags) + ".")
    parts.append("Текст сообщения (ненадёжные данные):\n<<<MESSAGE>>>\n" + text + "\n<<<END>>>")
    return "\n".join(parts)
